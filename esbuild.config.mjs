import esbuild from 'esbuild';
import process from 'process';
import fs from 'fs';
import path from 'path';
import builtins from 'builtin-modules';

const banner = '/*\nConfluence Space Sync for Obsidian. Generated by esbuild; the source is in src/.\n*/\n';
const production = process.argv[2] === 'production';
const pluginDir = process.env.OBSIDIAN_PLUGIN_DIR ?? '';

const copyToVault = {
  name: 'copy-to-vault',
  setup(build) {
    build.onEnd((result) => {
      if (result.errors.length > 0 || !pluginDir) {
        return;
      }
      fs.mkdirSync(pluginDir, { recursive: true });
      for (const file of ['main.js', 'manifest.json', 'styles.css']) {
        fs.copyFileSync(file, path.join(pluginDir, file));
      }
      console.log(`Copied plugin files to ${pluginDir}`);
    });
  }
};

let sourcemap = 'inline';
if (production) {
  sourcemap = false;
}

const context = await esbuild.context({
  banner: { js: banner },
  entryPoints: ['src/main.ts'],
  bundle: true,
  external: [
    'obsidian',
    'electron',
    '@codemirror/autocomplete',
    '@codemirror/collab',
    '@codemirror/commands',
    '@codemirror/language',
    '@codemirror/lint',
    '@codemirror/search',
    '@codemirror/state',
    '@codemirror/view',
    '@lezer/common',
    '@lezer/highlight',
    '@lezer/lr',
    ...builtins
  ],
  format: 'cjs',
  target: 'es2022',
  logLevel: 'info',
  sourcemap,
  treeShaking: true,
  outfile: 'main.js',
  plugins: [copyToVault]
});

if (production) {
  await context.rebuild();
  process.exit(0);
}
await context.watch();
